-- Skema setara database/schema.sql, khusus pengujian otomatis (SQLite). Jaga agar tetap sinkron.
CREATE TABLE users (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 username TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role TEXT NOT NULL DEFAULT 'kasir',
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE products (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 sku TEXT NOT NULL UNIQUE,
 nama TEXT NOT NULL,
 kategori TEXT NOT NULL DEFAULT 'Lainnya',
 harga INTEGER NOT NULL,
 stok INTEGER NOT NULL DEFAULT 0,
 stok_min INTEGER NOT NULL DEFAULT 0,
 pondok TEXT NOT NULL DEFAULT 'semua',
 aktif INTEGER NOT NULL DEFAULT 1,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE santri (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 nomor_induk TEXT NOT NULL UNIQUE,
 nama TEXT NOT NULL,
 pondok TEXT NOT NULL,
 saldo INTEGER NOT NULL DEFAULT 0,
 aktif INTEGER NOT NULL DEFAULT 1,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE orders (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 nomor TEXT NOT NULL UNIQUE,
 pondok TEXT NOT NULL,
 status TEXT NOT NULL,
 metode TEXT NOT NULL,
 subtotal INTEGER NOT NULL,
 diskon INTEGER NOT NULL DEFAULT 0,
 total INTEGER NOT NULL,
 santri_id INTEGER NULL,
 uang_diterima INTEGER NULL,
 kembalian INTEGER NULL,
 catatan TEXT NULL,
 created_by INTEGER NOT NULL,
 created_at TEXT NOT NULL,
 paid_at TEXT NULL
);
CREATE TABLE order_items (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 order_id INTEGER NOT NULL,
 product_id INTEGER NOT NULL,
 nama TEXT NOT NULL,
 harga INTEGER NOT NULL,
 qty INTEGER NOT NULL,
 subtotal INTEGER NOT NULL
);
CREATE TABLE stock_movements (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 product_id INTEGER NOT NULL,
 perubahan INTEGER NOT NULL,
 alasan TEXT NOT NULL,
 order_id INTEGER NULL,
 catatan TEXT NULL,
 created_by INTEGER NULL,
 created_at TEXT NOT NULL
);
CREATE TABLE santri_ledger (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 santri_id INTEGER NOT NULL,
 perubahan INTEGER NOT NULL,
 jenis TEXT NOT NULL,
 order_id INTEGER NULL,
 catatan TEXT NULL,
 created_by INTEGER NULL,
 created_at TEXT NOT NULL
);
CREATE TABLE payments (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 order_id INTEGER NOT NULL,
 provider TEXT NOT NULL,
 provider_ref TEXT NULL UNIQUE,
 qr_string TEXT NULL,
 status TEXT NOT NULL,
 amount INTEGER NOT NULL,
 expires_at TEXT NULL,
 paid_at TEXT NULL,
 raw_payload TEXT NULL,
 created_at TEXT NOT NULL
);
